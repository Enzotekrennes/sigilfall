//! The release files agree on their targets, trigger, installers and tool
//! version: `dist-workspace.toml`, the release workflow and the action that
//! installs dist (`.github/actions/install-dist`). Only their static
//! consistency is checked here: that a tag really produces the three
//! binaries is proved on GitHub.

use std::collections::BTreeSet;
use std::fs;
use std::path::Path;

// --- Release files: static consistency only -----------------------------------

/// The text of `file` from the line that starts with `start` up to, but not
/// including, the next line that starts with `end` (or to the end of the file).
fn section<'a>(file: &'a str, start: &str, end: &str) -> &'a str {
    let from = file
        .find(start)
        .unwrap_or_else(|| panic!("{start:?} is in the file"));
    let rest = &file[from..];
    let to = rest[start.len()..]
        .find(end)
        .map_or(rest.len(), |at| at + start.len());
    &rest[..to]
}

#[test]
fn the_release_files_agree_on_targets_trigger_installers_and_tool_version() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let dist = fs::read_to_string(root.join("dist-workspace.toml")).unwrap();
    let workflow = fs::read_to_string(root.join(".github/workflows/release.yml")).unwrap();
    let install_dist =
        fs::read_to_string(root.join(".github/actions/install-dist/action.yml")).unwrap();

    // One binary per system the README names: Windows, Linux, macOS.
    let targets = [
        "aarch64-apple-darwin",
        "x86_64-apple-darwin",
        "x86_64-unknown-linux-gnu",
        "x86_64-pc-windows-msvc",
    ];
    let listed: BTreeSet<&str> = dist
        .split("targets = [")
        .nth(1)
        .and_then(|rest| rest.split(']').next())
        .unwrap()
        .split('"')
        .skip(1)
        .step_by(2)
        .collect();
    assert_eq!(listed, targets.into_iter().collect::<BTreeSet<_>>());
    assert!(dist.contains("ci = \"github\""));
    assert!(dist.contains("installers = [\"shell\", \"powershell\"]"));
    assert!(dist.contains("[workspace]") && dist.contains("members = [\"cargo:.\"]"));
    // Every archive ships the notices of the crates and the French README
    // beside the files dist adds on its own (README.md, LICENSE-*).
    assert!(
        dist.contains("include = [\"THIRD-PARTY-LICENSES\", \"README.fr.md\"]"),
        "the archives include both files"
    );
    for file in ["THIRD-PARTY-LICENSES", "README.fr.md"] {
        assert!(root.join(file).is_file(), "{file} exists");
    }

    // The version of dist is the one of the configuration everywhere: in the
    // action that installs it, in the archive it downloads, and in the
    // header of the workflow `dist generate` wrote.
    let dist_version = dist
        .lines()
        .find_map(|line| line.strip_prefix("cargo-dist-version = \""))
        .and_then(|rest| rest.split('"').next())
        .unwrap();
    assert!(
        install_dist.contains(&format!("DIST_VERSION: \"{dist_version}\"")),
        "the action installs dist {dist_version}"
    );
    assert!(
        install_dist.contains("cargo-dist/releases/download/v$DIST_VERSION/"),
        "the action downloads the release of DIST_VERSION"
    );
    assert!(
        workflow.contains(&format!("(dist {dist_version})")),
        "the workflow was generated by dist {dist_version}"
    );

    // The action checks the archive of every runner that builds a target
    // against a pinned SHA-256 before installing it.
    for target in targets {
        assert!(
            install_dist.contains(&format!("cargo-dist-{target}.")),
            "the action has an archive for the runner of {target}"
        );
    }
    let hashes: Vec<&str> = install_dist
        .lines()
        .filter_map(|line| line.trim().strip_prefix("SHA256_"))
        .filter_map(|rest| rest.split_once(": "))
        .map(|(_, hash)| hash.trim())
        .collect();
    assert_eq!(hashes.len(), targets.len(), "one pinned hash per archive");
    for hash in &hashes {
        assert!(
            hash.len() == 64 && hash.chars().all(|c| c.is_ascii_hexdigit()),
            "{hash} is a SHA-256"
        );
    }
    assert!(install_dist.contains("\"$actual\" != \"$expected\""));
    // The archive is hashed from standard input: given a Windows path, which
    // holds backslashes, sha256sum and shasum prefix their output with "\"
    // and a correct hash would no longer match.
    assert!(install_dist.contains("sha256sum < \"$work_dir/$archive\""));
    assert!(install_dist.contains("shasum -a 256 < \"$work_dir/$archive\""));
    assert!(
        !install_dist.contains("sha256sum \"$") && !install_dist.contains("shasum -a 256 \"$"),
        "no archive is hashed by its file name"
    );

    // The workflow installs dist only through that action, never by piping
    // an unchecked installer into a shell.
    assert!(
        workflow
            .matches("uses: ./.github/actions/install-dist")
            .count()
            >= 2,
        "plan and build-local-artifacts install dist through the action"
    );
    assert!(!workflow.contains("cargo-dist/releases/download"));
    assert!(!workflow.contains("installer.sh") && !workflow.contains("installer.ps1"));

    // The workflow runs on a version tag; it reads the repository by
    // default and only `host`, which publishes, may write to it; the jobs
    // the README describes exist.
    assert!(workflow.contains("tags:\n      - '**[0-9]+.[0-9]+.[0-9]+*'"));
    assert!(workflow.contains("permissions:\n  \"contents\": \"read\""));
    assert_eq!(workflow.matches("\"contents\": \"write\"").count(), 1);
    assert!(
        section(&workflow, "\n  host:", "\n  announce:").contains("\"contents\": \"write\""),
        "write access belongs to the host job"
    );
    for job in [
        "plan:",
        "build-local-artifacts:",
        "build-global-artifacts:",
        "host:",
        "announce:",
    ] {
        assert!(workflow.contains(&format!("\n  {job}")), "{job}");
    }
    assert!(workflow.contains("gh release create"));
    assert!(
        workflow.contains("artifacts_matrix"),
        "the build matrix comes from `dist plan`"
    );
    // The runner overrides name targets of the list, plus `global` for the
    // jobs that run once, nothing else.
    let runners = section(
        &dist,
        "[dist.github-custom-runners]",
        "
[",
    );
    let runner_of = |key: &str| {
        runners
            .lines()
            .find_map(|line| line.strip_prefix(&format!("{key} = \"")))
            .and_then(|rest| rest.strip_suffix('"'))
            .unwrap_or_else(|| panic!("{key} has a runner override"))
    };
    for line in runners.lines().skip(1) {
        if let Some((key, _)) = line.split_once(" = ") {
            let key = key.trim();
            assert!(
                key == "global" || targets.contains(&key),
                "{key} is a target or `global`"
            );
        }
    }
    // Every runner is a versioned image GitHub still offers: a job asking
    // for a retired image (macos-14) is cancelled before it starts, which
    // left v0.1.0 without its macOS binaries, and ubuntu-22.04, the dist
    // default for Linux, is unsupported from April 2027. Both macOS targets
    // build on Apple Silicon: a suffixed label such as macos-15-intel fails
    // here. The action has a pinned dist archive for each of these runners.
    let image_version = |runner: &str, prefix: &str| {
        runner
            .strip_prefix(prefix)
            .and_then(|version| version.parse::<u32>().ok())
            .unwrap_or_else(|| panic!("{runner} is a versioned {prefix} image"))
    };
    for target in ["x86_64-apple-darwin", "aarch64-apple-darwin"] {
        let runner = runner_of(target);
        assert!(
            image_version(runner, "macos-") >= 15,
            "{runner} is an image GitHub still offers"
        );
    }
    for key in ["x86_64-unknown-linux-gnu", "global"] {
        let runner = runner_of(key);
        let year = runner
            .strip_prefix("ubuntu-")
            .and_then(|version| version.split_once('.'))
            .and_then(|(year, _)| year.parse::<u32>().ok())
            .unwrap_or_else(|| panic!("{runner} is a versioned Ubuntu image"));
        assert!(year >= 24, "{runner} is an image GitHub still offers");
    }
    let windows = runner_of("x86_64-pc-windows-msvc");
    assert!(
        image_version(windows, "windows-") >= 2022,
        "{windows} is an image GitHub still offers"
    );
    // release.yml is edited by hand (allow-dirty), so its jobs that run once
    // must ask for the `global` runner themselves.
    let global = format!("runs-on: \"{}\"", runner_of("global"));
    assert_eq!(
        workflow.matches("runs-on: \"").count(),
        workflow.matches(&global).count(),
        "every fixed runs-on of release.yml is the `global` runner"
    );
    assert_eq!(workflow.matches(&global).count(), 4);
    assert!(install_dist.contains("macOS/ARM64)"));
    // A tag `v<version>` matches the glob for the version of the crate.
    let version = fs::read_to_string(root.join("Cargo.toml"))
        .unwrap()
        .lines()
        .find_map(|line| {
            line.strip_prefix("version = \"")
                .map(|rest| rest.trim_end_matches('"').to_owned())
        })
        .unwrap();
    let tag = format!("v{version}");
    let digits: Vec<&str> = tag[1..].split('.').collect();
    assert!(
        tag.starts_with('v')
            && digits.len() == 3
            && digits
                .iter()
                .all(|d| d.chars().next().is_some_and(|c| c.is_ascii_digit())),
        "{tag}"
    );
    // Allow-dirty is declared: release.yml carries hardening that
    // `dist generate` does not write, so dist must not refuse it.
    assert!(dist.contains("allow-dirty = [\"ci\"]"));
}
