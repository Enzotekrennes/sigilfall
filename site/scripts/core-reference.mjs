// Generates the reference page of the `sigilfall-core` crate from the
// module documentation (`//!`) of its source files, so the page never
// drifts from the code: a wrong sentence is fixed in the Rust comment, then
// this script runs again (`npm run docs:api`, also run before `dev` and
// `build`).
//
// Writes `src/content/docs/reference/core.md`, one section per public
// module listed in `lib.rs`, in the order of `lib.rs`, each linking to the
// rustdoc page of the module under `api/` (published there by the docs
// workflow). It reads the Rust sources only; it does not run cargo.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(siteDir, '..', 'crates', 'sigilfall-core', 'src');
const outputFile = join(siteDir, 'src', 'content', 'docs', 'reference', 'core.md');

// Where the docs workflow copies `cargo doc --no-deps -p sigilfall-core`,
// under the site's base path.
const rustdocRoot = '/sigilfall/api/sigilfall_core';

/** Returns the `//!` lines at the head of a Rust file, without the marker. */
function moduleDoc(file) {
	const lines = readFileSync(file, 'utf8').split(/\r?\n/);
	const doc = [];
	for (const line of lines) {
		if (!line.startsWith('//!')) break;
		doc.push(line.replace(/^\/\/! ?/, ''));
	}
	if (doc.length === 0) {
		throw new Error(`${file} has no module documentation (//!); document it before regenerating the reference.`);
	}
	return doc;
}

/**
 * Turns rustdoc Markdown into plain Markdown for the site: intra-doc links
 * become code or text (their targets live in the rustdoc pages), and the
 * module's own headings move under the section heading of the module.
 */
function toSiteMarkdown(lines) {
	let inCode = false;
	return lines
		.map((line) => {
			if (line.startsWith('```')) {
				inCode = !inCode;
				return line;
			}
			if (inCode) return line;
			return line
				.replace(/^(#{1,3}) /, (_, hashes) => `${'#'.repeat(hashes.length + 2)} `)
				.replace(/\[(`[^`]+`)\]\([^)\s]+\)/g, '$1')
				.replace(/\[([^\]`]+)\]\((?:crate|super|self)::[^)]+\)/g, '$1')
				.replace(/\[(`[^`]+`)\](?!\()/g, '$1');
		})
		.join('\n')
		.trim();
}

const libLines = readFileSync(join(sourceDir, 'lib.rs'), 'utf8').split(/\r?\n/);
const modules = libLines
	.map((line) => line.match(/^pub mod ([a-z_]+);/))
	.filter(Boolean)
	.map((match) => match[1]);

const sections = modules.map((name) => {
	const doc = toSiteMarkdown(moduleDoc(join(sourceDir, `${name}.rs`)));
	return `## \`${name}\`\n\n${doc}\n\n[Rustdoc of \`${name}\`](${rustdocRoot}/${name}/index.html)`;
});

const page = `---
title: sigilfall-core
description: The public modules of the game's rules library, from the documentation of its source code.
editUrl: false
---

<!-- Generated by scripts/core-reference.mjs from the //! comments of crates/sigilfall-core/src. Do not edit: fix the Rust comment and run npm run docs:api. -->

${toSiteMarkdown(moduleDoc(join(sourceDir, 'lib.rs')))}

This page gathers the documentation at the head of each public module. The
[full rustdoc of the crate](${rustdocRoot}/index.html) lists every type,
function and constant with its own documentation.

${sections.join('\n\n')}
`;

mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(outputFile, page);
console.log(`Wrote ${modules.length} modules to ${outputFile}`);
